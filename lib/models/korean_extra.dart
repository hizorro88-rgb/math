/// 초성·중성·종성을 합쳐 글자 하나를 만든다 (ㄱ + ㅏ + ㅁ → 감)
String krCompose(String cho, String jung, [String jong = '']) {
  final c = _cho.indexOf(cho);
  final v = _jung.indexOf(jung);
  final t = jong.isEmpty ? 0 : _jong.indexOf(jong);
  assert(c >= 0 && v >= 0 && t >= 0, '$cho $jung $jong');
  return String.fromCharCode(0xAC00 + (c * 21 + v) * 28 + t);
}

